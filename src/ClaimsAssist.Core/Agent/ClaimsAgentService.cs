    private List<AITool> BuildTools(UserContext user, TurnTrace trace)
    {
        // One tool call can carry several queries (one per part of the question). They run in parallel,
        // which saves a model round trip per extra part compared with sequential searches.
        var search = AIFunctionFactory.Create(
            async (string[] queries, CancellationToken cancellationToken) =>
            {
                var distinct = queries.Where(q => !string.IsNullOrWhiteSpace(q)).Select(q => q.Trim())
                    .Distinct(StringComparer.OrdinalIgnoreCase).Take(4).ToList();
                var perQuery = await Task.WhenAll(distinct.Select(q => _retriever.SearchAsync(q, user, top: 5, cancellationToken)));

                var merged = new Dictionary<string, RetrievedChunk>(StringComparer.OrdinalIgnoreCase);
                for (var i = 0; i < distinct.Count; i++)
                {
                    trace.Retrievals.Add(new RetrievalEvent(distinct[i], perQuery[i].Select(r => new RetrievedRef(r.Chunk.ChunkId, r.Chunk.DocId, r.Score)).ToList()));
                    foreach (var r in perQuery[i])
                    {
                        if (!merged.TryGetValue(r.Chunk.ChunkId, out var existing) || existing.Score < r.Score)
                        {
                            merged[r.Chunk.ChunkId] = r;
                        }
                    }
                }

                var results = merged.Values.OrderByDescending(r => r.Score).Take(8).ToList();
                trace.QuarantinedSources.AddRange(results.Where(r => r.Chunk.RemovedSegments > 0).Select(r => r.Chunk.ChunkId).Except(trace.QuarantinedSources));
                if (results.Count == 0)
                {
                    return "No approved sources matched these queries for your role.";
                }

                return string.Join('\n', results.Select(r =>
                    $"<document chunk_id=\"{r.Chunk.ChunkId}\" title=\"{r.Chunk.DocTitle}\" section=\"{r.Chunk.Section}\" applies_to=\"{r.Chunk.AppliesTo}\" source=\"{r.Chunk.Source}\">\n{r.Chunk.Text}\n</document>"));
            },
            name: "search_knowledge",
            description: "Searches the approved claims knowledge base (policy wordings and claims guidelines, in English and German). Pass one query per part of the question (up to 4). Include German terms for German products and rules. Returns only passages the current user may read.");

        var getClaim = AIFunctionFactory.Create(
            (string claimId) =>
            {
                var claim = _claims.Find(claimId);
                if (claim is null)
                {
                    return $"Claim {claimId} not found.";
                }

                if (!ClaimStore.CanOpen(user, claim))
                {
                    trace.DeniedClaimIds.Add(claim.ClaimId);
                    return $"Access denied: your role may not open claim {claim.ClaimId}.";
                }

                trace.OpenedClaimIds.Add(claim.ClaimId);
                var rendered = ClaimStore.RenderForModel(claim, user, out var removed);
                if (removed > 0 && !trace.QuarantinedSources.Contains(claim.ClaimId))
                {
                    trace.QuarantinedSources.Add(claim.ClaimId);
                }

                return rendered;
            },
            name: "get_claim",
            description: "Opens a claim file by claim id (for example CLM-2026-0142), with data minimisation applied.");

        // The only write action: wrapped so the framework returns an approval request instead of running it.
        // The framework never runs it without approval; after approval, ResolveApprovalAsync runs the stored call
        // through the same executor.
        var proposeSettlement = new ApprovalRequiredAIFunction(AIFunctionFactory.Create(
            (string claimId, decimal amountEur, string rationale) => ProposeSettlement(user, trace, claimId, amountEur, rationale),
            name: "propose_settlement",
            description: "Proposes a settlement payment for a claim. Payment always goes to the IBAN on file. Requires human approval before it runs."));

        return [search, getClaim, proposeSettlement];
    }

    private async Task<ChatTurnResult> CompleteAsync(
        string conversationId,
        string question,
        UserContext user,
        TurnTrace trace,
        AgentResponse response,
        TimeSpan elapsed,
        CancellationToken cancellationToken)
    {
        trace.ModelRuns++;
        trace.LatencyMs += (long)elapsed.TotalMilliseconds;
        trace.InputTokens += response.Usage?.InputTokenCount ?? 0;
        trace.OutputTokens += response.Usage?.OutputTokenCount ?? 0;
        RecordToolActivity(trace, response.Messages);

        var approvals = response.Messages.SelectMany(m => m.Contents).OfType<ToolApprovalRequestContent>().ToList();
        if (approvals.Count > 0)
        {
            var approvalId = NewId("apr");
            var calls = approvals.Select(a => new ApprovedCall(a.ToolCall is FunctionCallContent f ? f.CallId : approvalId, ToolName(a.ToolCall), ArgumentsJson(a.ToolCall))).ToList();
            var now = _time.GetUtcNow();
            var record = new PendingApprovalRecord(approvalId, conversationId, question, RequesterSnapshot.Of(user), calls, trace, now, now + _approvalTtl);
            if (!await _approvals.TryAddAsync(record, cancellationToken))
            {
                var full = new ChatTurnResult(
                    conversationId,
                    "answered",
                    "Too many approvals are waiting. Decide or let pending approvals expire before proposing another settlement.",
                    false,
                    [],
                    [],
                    Warnings(trace),
                    AiDisclosure,
                    trace);
                Audit(conversationId, user, question, full);
                return full;
            }

            var waiting = new ChatTurnResult(
                conversationId,
                "approval_required",
                "This action needs human approval before it runs.",
                true,
                [],
                calls.Select(c => new PendingApproval(approvalId, c.Tool, c.ArgumentsJson)).ToList(),
                Warnings(trace),
                AiDisclosure,
                trace);
            Audit(conversationId, user, question, waiting);
            return waiting;
        }

        var finalText = response.Messages.LastOrDefault(m => m.Role == ChatRole.Assistant && !string.IsNullOrWhiteSpace(m.Text))?.Text
            ?? response.Text;
        var answer = ParseAnswer(finalText);
        trace.SuspiciousContentDetected |= answer.SuspiciousContentDetected || trace.QuarantinedSources.Count > 0;
        return Finish(conversationId, question, user, trace, answer);
    }

    /// <summary>The output pipeline every answer goes through, model-written or not: citations checked, unapproved links
    /// removed, PII redacted, figures grounded, audited, AI disclosure attached.</summary>
    /// <param name="user">Whom the turn is audited under: the asker, or for a decision the approver.</param>
    private ChatTurnResult Finish(string conversationId, string question, UserContext user, TurnTrace trace, AgentAnswer answer)
    {
        var citations = ResolveCitations(answer.Citations.Concat(InlineCitations(answer.Answer)), trace);

        // Output guards: no links to unapproved hosts, and no IBAN, e-mail, phone number or date of birth,
        // even if the model slips. Deterministic, so they hold regardless of what the model does.
        var linkFree = UntrustedContentGuard.RemoveUnapprovedLinks(answer.Answer, _allowedLinkHosts);
        trace.RemovedLinks += linkFree.Removed;
        var (safeAnswer, redactions) = _redactor.Redact(linkFree.Text, includeNames: false);
        trace.OutputRedactions += redactions;

        // Figure grounding: every number, date and claim id the handler sees must be in a cited source, a tool result
        // of this turn or the question. Runs on the text as shown (after redaction); see GroundingVerifier.
        var shown = GroundingVerifier.ForHandler(safeAnswer, answer.AnswerFound,
            GroundingVerifier.SourcesFrom(trace.GroundingContext, citations.Select(c => c.Ref)), question, trace.OpenedClaimIds);
        trace.GroundingStatements += shown.Check.Statements;
        trace.GroundingWithheld += shown.Check.Withheld;
        trace.GroundingMissing.AddRange(shown.Check.Missing.Except(trace.GroundingMissing));

        var result = new ChatTurnResult(conversationId, "answered", shown.Answer, shown.AnswerFound, citations, [], Warnings(trace), AiDisclosure, trace);
        Audit(conversationId, user, question, result);
        return result;
    }

    private ChatTurnResult Blocked(string conversationId, string question, UserContext user, TurnTrace trace, ClientResultException ex, TimeSpan elapsed)
    {
        trace.ModelRuns++;
        trace.LatencyMs += (long)elapsed.TotalMilliseconds;
        trace.ContentFilterTriggered = true;
        trace.ContentFilterCategories = FilterCategories(ex);
        var result = new ChatTurnResult(
            conversationId,
            "blocked",
            "This request was blocked by the content safety filter. Ask about a claim, a policy or a claims guideline instead.",
            false,
            [],
            [],
            [$"Blocked by the Azure OpenAI content filter ({trace.ContentFilterCategories})."],
            AiDisclosure,
            trace);
        Audit(conversationId, user, question, result);
        return result;
    }

    private static List<string> Warnings(TurnTrace trace)
    {
        var warnings = new List<string>();
        if (trace.QuarantinedSources.Count > 0)
        {
            warnings.Add($"A source for this answer contained hidden text or instructions addressed to an AI assistant ({string.Join(", ", trace.QuarantinedSources)}). It was removed and ignored. Report the document to IT security.");
        }

        if (trace.RemovedLinks > 0)
        {
            warnings.Add("A link to an unapproved website was removed from this answer.");
        }

        if (trace.GroundingWithheld > 0)
        {
            warnings.Add("Part of this answer was withheld: a figure in it could not be found in the cited sources.");
        }

        return warnings;
    }

    private static bool IsContentFilter(ClientResultException ex) =>
        ex.Status == 400 && ex.Message.Contains("content_filter", StringComparison.OrdinalIgnoreCase);

    private static string FilterCategories(ClientResultException ex)
    {
        try
        {
            var raw = ex.GetRawResponse()?.Content?.ToString();
            if (raw is not null)
            {
                using var doc = JsonDocument.Parse(raw);
                if (doc.RootElement.TryGetProperty("error", out var error)
                    && error.TryGetProperty("innererror", out var inner)
                    && inner.TryGetProperty("content_filter_result", out var filters))
                {
                    var flagged = filters.EnumerateObject()
                        .Where(p => p.Value.ValueKind == JsonValueKind.Object && p.Value.TryGetProperty("filtered", out var f) && f.ValueKind == JsonValueKind.True)
                        .Select(p => p.Name)
                        .ToList();
                    if (flagged.Count > 0)
                    {
                        return string.Join(", ", flagged);
                    }
                }
            }
        }
        catch (JsonException)
        {
            // Fall through to the generic category.
        }

        return "prompt";
    }

    private static void RecordToolActivity(TurnTrace trace, IEnumerable<ChatMessage> messages)
    {
        foreach (var content in messages.SelectMany(m => m.Contents))
        {
            switch (content)
            {
                case ToolApprovalRequestContent { ToolCall: FunctionCallContent approvalCall }:
                    Upsert(trace, approvalCall).RequiresApproval = true;
                    break;
                case FunctionCallContent call:
                    Upsert(trace, call);
                    break;
                case FunctionResultContent result:
                    var text = result.Result?.ToString() ?? string.Empty;
                    var evt = trace.ToolCalls.FirstOrDefault(e => e.CallId == result.CallId);
                    if (evt is not null)
                    {
                        evt.Executed = true;
                        evt.Outcome = text.Length > 300 ? text[..300] + "…" : text;
                    }

                    if (text.Length > 0 && !trace.GroundingContext.Contains(text))
                    {
                        trace.GroundingContext.Add(text);
                    }

                    break;
            }
        }
    }

    private static ToolEvent Upsert(TurnTrace trace, FunctionCallContent call)
    {
        var existing = trace.ToolCalls.FirstOrDefault(e => e.CallId == call.CallId);
        if (existing is not null)
        {
            return existing;
        }

        var created = new ToolEvent { CallId = call.CallId, Name = call.Name, ArgumentsJson = ArgumentsJson(call) };
        trace.ToolCalls.Add(created);
        return created;
    }

    private IReadOnlyList<Citation> ResolveCitations(IEnumerable<string> raw, TurnTrace trace)
    {
        var retrieved = trace.Retrievals.SelectMany(r => r.Results).Select(r => r.ChunkId).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var opened = trace.OpenedClaimIds.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var citations = new List<Citation>();

        foreach (var reference in raw.Select(r => r.Trim().Trim('[', ']').Trim()).Where(r => r.Length > 0).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            if (retrieved.Contains(reference) && _chunksById.TryGetValue(reference, out var chunk))
            {
                citations.Add(new Citation(chunk.ChunkId, chunk.DocId, chunk.DocTitle, chunk.Section));
            }
            else if (retrieved.FirstOrDefault(id => id.StartsWith(reference + "#", StringComparison.OrdinalIgnoreCase)) is { } docLevel
                     && _chunksById.TryGetValue(docLevel, out var docChunk))
            {
                citations.Add(new Citation(docChunk.ChunkId, docChunk.DocId, docChunk.DocTitle, docChunk.Section));
            }
            else if (opened.Contains(reference))
            {
                citations.Add(new Citation(reference.ToUpperInvariant(), null, $"Claim file {reference.ToUpperInvariant()}", null));
            }
            else
            {
                // Hallucinated, or not retrieved for this user: dropped, never shown, but counted by the gate.
                trace.InvalidCitations.Add(reference);
            }
        }

        return citations.DistinctBy(c => c.Ref).ToList();
    }

    private static AgentAnswer ParseAnswer(string? text)
    {
        var raw = (text ?? string.Empty).Trim();
        if (raw.StartsWith("```", StringComparison.Ordinal))
        {
            raw = CodeFence().Replace(raw, string.Empty).Trim();
        }

        try
        {
            var parsed = JsonSerializer.Deserialize<AgentAnswer>(raw, Json);
            if (parsed is not null && !string.IsNullOrWhiteSpace(parsed.Answer))
            {
                return parsed;
            }
        }
        catch (JsonException)
        {
            // Fall through: treat the text as a plain answer.
        }

        return new AgentAnswer { Answer = raw, AnswerFound = raw.Length > 0 };
    }

    private static IEnumerable<string> InlineCitations(string answer) =>
        InlineCitation().Matches(answer).Select(m => m.Groups[1].Value);

    private void Audit(string conversationId, UserContext user, string question, ChatTurnResult result)
    {
        var t = result.Trace;
        _audit.Write(new AuditRecord(
            DateTimeOffset.UtcNow,
            conversationId,
            _audit.Pseudonymise(user.UserId),
            result.Status,
            question,
            result.Answer,
            t.Retrievals.SelectMany(r => r.Results.Select(x => x.ChunkId)).Distinct().ToList(),
            t.ToolCalls.Select(c => $"{c.Name} {c.ArgumentsJson} => {(c.Executed ? Shorten(c.Outcome) : c.Approved == false ? "rejected by the approver" : c.RequiresApproval ? "awaiting approval" : "requested")}").ToList(),
            t.InputTokens,
            t.OutputTokens,
            t.LatencyMs));
    }

    private static string Shorten(string? text) => text is null ? string.Empty : text.Length > 80 ? text[..80] + "…" : text;

    private static string ToolName(ToolCallContent call) => call is FunctionCallContent f ? f.Name : call.GetType().Name;

    private static string ArgumentsJson(ToolCallContent call) =>
