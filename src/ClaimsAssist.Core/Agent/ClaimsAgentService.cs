    public async Task<ChatTurnResult> AskAsync(
        string question,
        UserContext user,
        string? conversationId = null,
        CancellationToken cancellationToken = default)
    {
        var trace = new TurnTrace { Model = _model };
        var agent = CreateAgent(user, trace);
        var session = await agent.CreateSessionAsync(cancellationToken);
        conversationId ??= NewId("c");
        var started = Stopwatch.GetTimestamp();
        try
        {
            var response = await agent.RunAsync(question, session, cancellationToken: cancellationToken);
            return await CompleteAsync(conversationId, question, user, trace, response, Stopwatch.GetElapsedTime(started), cancellationToken);
        }
        catch (ClientResultException ex) when (IsContentFilter(ex))
        {
            return Blocked(conversationId, question, user, trace, ex, Stopwatch.GetElapsedTime(started));
        }
    }

    /// <summary>
    /// Decides a pending approval. The stored call runs itself (the model is not asked again), through the same
    /// settlement code the tool uses, so its guards run after approval exactly as they would have before. At most one
    /// decision wins: the approver is checked first (a wrong approver never consumes the approval), then the record is
    /// taken atomically from the store.
    /// </summary>
    public async Task<ChatTurnResult?> ResolveApprovalAsync(
        string approvalId,
        bool approve,
        string? reason,
        UserContext approver,
        CancellationToken cancellationToken = default)
    {
        var pending = await _approvals.GetAsync(approvalId, cancellationToken);
        if (pending is null)
        {
            return null;
        }

        // Human in the loop: the requesting handler confirms, or a member of an approver group (configuration, for
        // example the team leads) decides: four-eyes for escalations.
        var byRequester = approver.UserId == pending.Requester.UserId;
        if (!byRequester && !_approverGroups.Any(approver.IsIn))
        {
            throw new UnauthorizedAccessException("Only the requesting handler or a team lead can decide on this approval.");
        }

        var taken = await _approvals.TryTakeAsync(approvalId, cancellationToken);
        if (taken is null)
        {
            return null; // decided concurrently, or expired in between
        }

        // The requester's own decision runs with their identity as resolved now, so revoked authority cannot execute.
        // A team lead's decision keeps the requester's authority, as before approvals were stored.
        var actor = byRequester ? approver : taken.Requester.ToUserContext();
        var trace = taken.Trace;
        var answers = new List<string>();
        var cited = new List<string>();
        if (!approve && !string.IsNullOrWhiteSpace(reason))
        {
            // The approver's own words are a source for the reply, as the handler's question is.
            trace.GroundingContext.Add("Decision note: " + reason.Trim());
        }

        foreach (var call in taken.Calls)
        {
            var tool = trace.ToolCalls.FirstOrDefault(t => t.CallId == call.CallId);
            if (tool is not null)
            {
                tool.Approved = approve;
            }

            if (!approve)
            {
                // No name here: the answer goes to the audit log, where people appear only as pseudonyms.
                answers.Add($"Not run: the approver rejected the {call.Tool} request" + (string.IsNullOrWhiteSpace(reason) ? "." : $" ({reason.Trim()})."));
                continue;
            }

            trace.ApprovalsGranted++;
            var (outcome, claimId) = RunApproved(call, actor, trace);
            if (tool is not null)
            {
                tool.Executed = true;
                tool.Outcome = outcome;
            }

            trace.GroundingContext.Add(outcome); // the confirmation's figures come from here
            var citable = trace.OpenedClaimIds.FirstOrDefault(id => string.Equals(id, claimId, StringComparison.OrdinalIgnoreCase));
            answers.Add(citable is null ? outcome : $"{outcome} [{citable}]");
            if (citable is not null)
            {
                cited.Add(citable);
            }
        }

        // Audited under the person who decided (the request was audited under the requester; the conversation id links
        // the two): the evidence of human oversight.
        var confirmation = new AgentAnswer { Answer = string.Join("\n\n", answers), AnswerFound = true, Citations = cited };
        return Finish(taken.ConversationId, taken.Question, approver, trace, confirmation);
    }

    /// <summary>Runs a stored, approved call with the arguments the approver saw. The only write tool is
    /// propose_settlement; anything else is refused, never guessed.</summary>
    private (string Outcome, string ClaimId) RunApproved(ApprovedCall call, UserContext actor, TurnTrace trace)
    {
        if (call.Tool != "propose_settlement")
        {
            return ($"REJECTED: {call.Tool} cannot run after approval.", string.Empty);
        }

        string claimId, rationale;
        decimal amount;
        try
        {
            using var args = JsonDocument.Parse(call.ArgumentsJson);
            var root = args.RootElement;
            claimId = root.TryGetProperty("claimId", out var id) && id.ValueKind == JsonValueKind.String ? id.GetString()! : string.Empty;
            rationale = root.TryGetProperty("rationale", out var why) && why.ValueKind == JsonValueKind.String ? why.GetString()! : string.Empty;
            // Read exactly as the tool binds its argument (web defaults: a number, or a number in a string).
            amount = root.TryGetProperty("amountEur", out var a) ? JsonSerializer.Deserialize<decimal>(a.GetRawText(), Json) : 0;
        }
        catch (JsonException)
        {
            return ("REJECTED: the stored request could not be read.", string.Empty);
        }

        // A missing amount stays 0, which the settlement guards reject.
        return (ProposeSettlement(actor, trace, claimId, amount, rationale), claimId);
    }

    /// <summary>The one settlement executor: the tool's body and the post-approval path both call it, so their guards
    /// can never differ.</summary>
    private string ProposeSettlement(UserContext user, TurnTrace trace, string claimId, decimal amountEur, string rationale)
    {
        var outcome = _settlements.Propose(claimId, amountEur, rationale, user);
        trace.WriteActions.Add(new WriteAction("propose_settlement", claimId, amountEur, outcome.Outcome, outcome.Message));

        // The tool read this claim under the user's permissions, so the claim is a legitimate citation
        // for the answer (gate run 3 showed valid claim citations being dropped without this).
        if (_claims.Find(claimId) is { } claim && ClaimStore.CanOpen(user, claim) && !trace.OpenedClaimIds.Contains(claim.ClaimId))
        {
            trace.OpenedClaimIds.Add(claim.ClaimId);
        }

        return $"{outcome.Outcome}: {outcome.Message}";
    }

